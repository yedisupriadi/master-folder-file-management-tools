import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const core=fs.readFileSync('folder-manager-core.html','utf8');
const actions=fs.readFileSync('folder-manager-register-actions.js','utf8');
const flatten=fs.readFileSync('folder-manager-flatten.js','utf8');
const notFound=()=>Object.assign(new Error('Missing'),{name:'NotFoundError'});
const denied=()=>Object.assign(new Error('Denied'),{name:'NotAllowedError'});
let written=[],removed=[],aborted=0,alerts=[];
const source={getFile:async()=>new Blob(['original-content'])};
let folder={getFileHandle:async()=>{throw notFound();},getDirectoryHandle:async()=>{throw notFound();},removeEntry:async name=>removed.push(name)};
const context=vm.createContext({Blob,Error,console,regBusy:false,cur:()=>folder,regRefresh(){},regExt:()=>'.docx',fncTxt:en=>en,TL:en=>en,
  state:{entries:[{kind:'file',name:'source.docx',handle:source}]},confirm:()=>true,alert:message=>alerts.push(message),loadCurrent:async()=>{}});
vm.runInContext(core.slice(core.indexOf('  async function itemExists'),core.indexOf('  function fmtSize')),context);
vm.runInContext(flatten.slice(flatten.indexOf('async function flattenItemExists'),flatten.indexOf('async function flattenUniqueFileName')),context);
vm.runInContext(actions.slice(actions.indexOf('async function regActionRenameFile'),actions.indexOf('function regActionViewRecord')),context);
assert.equal(await context.regActionRenameFile('source.docx','source'),false);assert.equal(removed.length,0);
folder.getFileHandle=async()=>({});
assert.equal(await context.regActionRenameFile('source.docx','target'),false);assert.equal(removed.length,0);
folder.getFileHandle=async()=>{throw denied();};
assert.equal(await context.regActionRenameFile('source.docx','target'),false);assert.equal(removed.length,0);
console.log('✓ Rename rejects no-ops, live target collisions and permission failures without deleting source');
folder.getFileHandle=async(name,options)=>{if(!options?.create)throw notFound();return{createWritable:async()=>({write:async()=>{throw new Error('Disk full');},close:async()=>{},abort:async()=>{aborted++;}})};};
assert.equal(await context.regActionRenameFile('source.docx','target'),false);assert.equal(removed.length,0);assert.equal(aborted,1);
console.log('✓ Failed write aborts its writable stream and retains the original file');
folder.getFileHandle=async(name,options)=>{if(!options?.create)throw notFound();return{createWritable:async()=>({write:async blob=>{written.push(await blob.text());},close:async()=>{written.push('closed');},abort:async()=>{}})};};
folder.removeEntry=async name=>{assert.equal(written.at(-1),'closed');removed.push(name);};
assert.equal(await context.regActionRenameFile('source.docx','target'),true);assert.deepEqual(written,['original-content','closed']);assert.deepEqual(removed,['source.docx']);
console.log('✓ Fallback rename closes a complete copy before removing its source');
let checks=0,release;
folder.getFileHandle=()=>{checks++;return new Promise(r=>{release=r;});};
const pending=context.regActionRenameFile('source.docx','target');
assert.equal(await context.regActionRenameFile('source.docx','target'),false);assert.equal(checks,1);release({});await pending;
console.log('✓ Rename locks before asynchronous collision checks, preventing duplicate operations');
folder.getFileHandle=async name=>{if(name==='report.pdf')return{};throw notFound();};
assert.equal(await context.uniqueName(folder,'report.pdf'),'report (2).pdf');
folder.getFileHandle=async()=>{throw denied();};await assert.rejects(()=>context.uniqueName(folder,'report.pdf'),{name:'NotAllowedError'});
await assert.rejects(()=>context.isSelfOrDescendant({isSameEntry:async()=>{throw denied();}},folder),/Could not verify/);
console.log('✓ Copy collision names preserve extensions; unverifiable destinations fail closed');

const storage=vm.createContext({Map,Event,document:{documentElement:{dataset:{}},addEventListener(){}},addEventListener(){},localStorage:{getItem(){throw denied();},setItem(){throw denied();},removeItem(){throw denied();}}});
storage.window=storage;
vm.runInContext(fs.readFileSync('scripts/tool-ui.js','utf8'),storage);
storage.ToolStorage.setItem('profile','saved');assert.equal(storage.ToolStorage.getItem('profile'),'saved');storage.ToolStorage.removeItem('profile');assert.equal(storage.ToolStorage.getItem('profile'),null);
assert.equal(storage.document.documentElement.lang,'id');
console.log('✓ Blocked browser storage retains a usable in-memory session and valid preferences');
